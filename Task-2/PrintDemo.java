class PrintDemo{
	public static void main(String arg[]) {
		//using println
		System.out.println("my name is ramsan");
		System.out.println("my father name thaventhiran");
		System.out.println("my age 25");
		
		System.out.println();
		
		//using print
		System.out.print("my name is ramsan");
		System.out.print("my father name thaventhiran");
		System.out.print("my age 25");
		
		System.out.println();
		
		//using print with\n
		System.out.print("my name is ramsan\n");
		System.out.print("my father name thaventhiran\n");
		System.out.print("my age 25\n");
	}
}
